const dictionaries = { en, zh, ja };
let current = en;

/** choice: 'auto' | 'en' | 'zh' | 'ja'; locale: the system's, used for 'auto'. */
export function setLanguage(choice, locale) {
  let lang = choice;
  if (!dictionaries[lang]) {
    const l = (locale || 'en').toLowerCase();
    lang = l.startsWith('zh') ? 'zh' : l.startsWith('ja') ? 'ja' : 'en';
  }
  current = dictionaries[lang];
  document.documentElement.dataset.lang = lang === 'zh' ? 'zh-CN' : lang;
}

export function t(key, vars, fallback) {
  let s = current[key] ?? en[key] ?? fallback ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}
