#!/usr/bin/env bash
# HdrCast relay setup: generates credentials, writes relay/mediamtx.yml + relay/.env,
# and prints the URLs / GUI fields for the sender and the viewers.
#
# Usage: relay/setup.sh [options]
#   --public-host HOST   public IP or DDNS name friends connect to (stored in .env; default placeholder)
#   --lan-host IP        LAN IP of this box the sender publishes to (default: auto-detect, fallback 192.168.1.201)
#   --regenerate         replace an existing .env with new secrets without asking
#   --keep               keep an existing .env without asking (non-interactive safe default)
#   --print              only print the URLs from the existing .env (no files written)
#   -h, --help
#
# Idempotent: running it again keeps the existing secrets unless you confirm (or pass --regenerate).
# mediamtx.yml is always re-rendered from mediamtx.template.yml so the two files never drift apart.
set -euo pipefail

RELAY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TEMPLATE="$RELAY_DIR/mediamtx.template.yml"
CONFIG="$RELAY_DIR/mediamtx.yml"
ENV_FILE="$RELAY_DIR/.env"

SRT_PORT=8890
HLS_PORT=8888
PUBLIC_HOST=""
LAN_HOST=""
MODE="ask"          # ask | regenerate | keep | print

usage() { sed -n '2,15p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
  case "$1" in
    --public-host) PUBLIC_HOST="${2:-}"; shift 2 ;;
    --lan-host)    LAN_HOST="${2:-}"; shift 2 ;;
    --regenerate)  MODE="regenerate"; shift ;;
    --keep)        MODE="keep"; shift ;;
    --print)       MODE="print"; shift ;;
    -h|--help)     usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

[ -f "$TEMPLATE" ] || { echo "ERROR: template not found: $TEMPLATE" >&2; exit 1; }

# Random token from [A-Za-z0-9]: safe inside the SRT streamid and URL query without percent-encoding.
gen_token() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1"; echo; }

detect_lan_ip() {
  local ip=""
  if command -v hostname >/dev/null 2>&1; then ip="$(hostname -I 2>/dev/null | awk '{print $1}')" || true; fi
  if [ -z "$ip" ] && command -v ip >/dev/null 2>&1; then
    ip="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}')" || true
  fi
  echo "${ip:-192.168.1.201}"
}

load_env() {
  # shellcheck disable=SC1090
  set -a; . "$ENV_FILE"; set +a
}

write_env() {
  umask 077
  cat > "$ENV_FILE" <<ENV
# HdrCast relay secrets - generated by relay/setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit.
HDRCAST_SENDER_USER=sender
HDRCAST_SENDER_PW=$HDRCAST_SENDER_PW
HDRCAST_VIEWER_USER=viewer
HDRCAST_VIEWER_PW=$HDRCAST_VIEWER_PW
HDRCAST_PUBLISH_PASSPHRASE=$HDRCAST_PUBLISH_PASSPHRASE
HDRCAST_READ_PASSPHRASE=$HDRCAST_READ_PASSPHRASE
HDRCAST_PATH=screen
HDRCAST_SRT_PORT=$SRT_PORT
HDRCAST_HLS_PORT=$HLS_PORT
HDRCAST_LAN_HOST=$HDRCAST_LAN_HOST
HDRCAST_PUBLIC_HOST=$HDRCAST_PUBLIC_HOST
ENV
}

render_config() {
  # sed is safe here: tokens are [A-Za-z0-9] only (no sed metacharacters).
  sed -e "s/__SENDER_PW__/$HDRCAST_SENDER_PW/" \
      -e "s/__VIEWER_PW__/$HDRCAST_VIEWER_PW/" \
      -e "s/__PUBLISH_PASSPHRASE__/$HDRCAST_PUBLISH_PASSPHRASE/" \
      -e "s/__READ_PASSPHRASE__/$HDRCAST_READ_PASSPHRASE/" \
      "$TEMPLATE" > "$CONFIG.tmp"
  if grep -q '__[A-Z_]*__' "$CONFIG.tmp"; then
    echo "ERROR: unreplaced placeholder in rendered config" >&2; rm -f "$CONFIG.tmp"; exit 1
  fi
  chmod 600 "$CONFIG.tmp"
  mv "$CONFIG.tmp" "$CONFIG"
}

# ---- decide: new secrets or existing ones ---------------------------------------------------
if [ -f "$ENV_FILE" ]; then
  case "$MODE" in
    print|keep) load_env ;;
    regenerate) : ;;
    ask)
      if [ -t 0 ]; then
        printf 'relay/.env already exists. Generate NEW secrets and overwrite it? (existing viewers/sender will need the new values) [y/N] '
        read -r ans
        case "$ans" in y|Y|yes|YES) MODE="regenerate" ;; *) MODE="keep"; load_env ;; esac
      else
        echo "relay/.env already exists and stdin is not a terminal: keeping existing secrets (use --regenerate to replace)."
        MODE="keep"; load_env
      fi ;;
  esac
else
  [ "$MODE" = "print" ] && { echo "ERROR: $ENV_FILE does not exist; run without --print first." >&2; exit 1; }
  MODE="regenerate"
fi

if [ "$MODE" = "regenerate" ]; then
  HDRCAST_SENDER_PW="$(gen_token 20)"
  HDRCAST_VIEWER_PW="$(gen_token 20)"
  HDRCAST_PUBLISH_PASSPHRASE="$(gen_token 24)"   # SRT passphrase: 10-79 chars
  HDRCAST_READ_PASSPHRASE="$(gen_token 24)"
fi

# Hosts: CLI flag > existing .env value > auto-detect / placeholder
HDRCAST_LAN_HOST="${LAN_HOST:-${HDRCAST_LAN_HOST:-$(detect_lan_ip)}}"
HDRCAST_PUBLIC_HOST="${PUBLIC_HOST:-${HDRCAST_PUBLIC_HOST:-YOUR_PUBLIC_IP_OR_DDNS}}"
SRT_PORT="${HDRCAST_SRT_PORT:-$SRT_PORT}"
HLS_PORT="${HDRCAST_HLS_PORT:-$HLS_PORT}"

if [ "$MODE" != "print" ]; then
  write_env
  render_config
  echo "wrote $ENV_FILE (mode 600)"
  echo "wrote $CONFIG (rendered from $(basename "$TEMPLATE"))"
fi

# ---- derived values --------------------------------------------------------------------------
# Sender -> relay is on the LAN: 800 ms is plenty (design.md section 5).
SENDER_LATENCY_US=800000
EXAMPLE_MBPS=40
INPUTBW=$(( EXAMPLE_MBPS * 1000000 / 8 ))      # bytes/s (ffmpeg srt inputbw unit)
# Reader buffers sized for up to ~100 Mbps x 6 s: packets = latency_s * bitrate / 10528; ffs >= packets; rcvbuf <= ffs*1472.
READER_BUF="rcvbuf=64000000&ffs=64000&recv_buffer_size=8000000"

publish_url() {
  echo "srt://$HDRCAST_LAN_HOST:$SRT_PORT?streamid=publish:screen:sender:$HDRCAST_SENDER_PW&passphrase=$HDRCAST_PUBLISH_PASSPHRASE&pbkeylen=32&pkt_size=1316&transtype=live&latency=$SENDER_LATENCY_US&maxbw=0&inputbw=$INPUTBW&oheadbw=25&sndbuf=64000000&ffs=64000&connect_timeout=5000"
}
read_url() { # $1 = host, $2 = latency ms
  echo "srt://$1:$SRT_PORT?streamid=read:screen:viewer:$HDRCAST_VIEWER_PW&passphrase=$HDRCAST_READ_PASSPHRASE&latency=$(( $2 * 1000 ))&$READER_BUF"
}

rmem="$(sysctl -n net.core.rmem_max 2>/dev/null || cat /proc/sys/net/core/rmem_max 2>/dev/null || echo 0)"

cat <<OUT

================ HdrCast relay: credentials (also in relay/.env) ================
  sender  user/password : sender / $HDRCAST_SENDER_PW
  viewer  user/password : viewer / $HDRCAST_VIEWER_PW
  publish passphrase    : $HDRCAST_PUBLISH_PASSPHRASE   (SRT AES-256 key, sender leg)
  read    passphrase    : $HDRCAST_READ_PASSPHRASE   (SRT AES-256 key, viewer leg)
  path                  : screen

================ Sender (HdrCastSender.exe -> Target: Relay) ====================
  host $HDRCAST_LAN_HOST   port $SRT_PORT   user sender   password (above)   passphrase = publish passphrase   latency 800 ms
  raw ffmpeg output URL (example for $EXAMPLE_MBPS Mbps; inputbw = bitrate/8 bytes/s, latency in MICROSECONDS):
    $(publish_url)

================ Viewers (HdrCastReceiver.exe) ==================================
  host $HDRCAST_PUBLIC_HOST   port $SRT_PORT   user viewer   password (above)   passphrase = read passphrase
  latency presets: Japan 1500 ms / Australia 2000 ms / China 3500 ms
  raw mpv URLs (latency in MICROSECONDS; rcvbuf/ffs are REQUIRED above ~40 Mbps):
    Japan     : $(read_url "$HDRCAST_PUBLIC_HOST" 1500)
    Australia : $(read_url "$HDRCAST_PUBLIC_HOST" 2000)
    China     : $(read_url "$HDRCAST_PUBLIC_HOST" 3500)
  LAN test from another PC at home:
    $(read_url "$HDRCAST_LAN_HOST" 1500)
  HLS browser fallback (SDR look depends on the browser):
    http://viewer:$HDRCAST_VIEWER_PW@$HDRCAST_PUBLIC_HOST:$HLS_PORT/screen

================ Reminders =======================================================
  1. Router: forward UDP $SRT_PORT -> $HDRCAST_LAN_HOST (optional: TCP $HLS_PORT for HLS). Direction: inbound. Nothing else.
  2. Host sysctl (net.core.rmem_max is currently $rmem; mediamtx.yml needs >= 4000000, 16 MB recommended):
       sudo sysctl -w net.core.rmem_max=16777216
       echo 'net.core.rmem_max=16777216' | sudo tee /etc/sysctl.d/99-hdrcast.conf
  3. Start / stop / logs:  relay/up.sh   relay/down.sh   relay/logs.sh
  4. Public host is "$HDRCAST_PUBLIC_HOST": set it with  relay/setup.sh --public-host <ip-or-ddns>  (secrets are kept).
  5. Self-test on this box (no Windows needed):  relay/selftest.sh   (uses temporary secrets, leaves the relay down)
OUT
if [ "$rmem" -lt 4000000 ] 2>/dev/null; then
  echo "WARNING: net.core.rmem_max=$rmem < 4000000 -> MediaMTX will FAIL to open the SRT listener. Run step 2 first." >&2
fi
