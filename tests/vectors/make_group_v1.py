#!/usr/bin/env python3
"""Regenerates tests/vectors/group-v1.json (docs/design.md section 8).

The vectors pin every byte of the v1 formats so the C# client and signal/hdrcast_signal.py cannot drift apart.
Inputs are fixed; run it only when the protocol version changes.
"""
import base64, hashlib, hmac, json, os, struct


def b64u(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).decode("ascii").rstrip("=")


def sub(k: bytes, label: str) -> bytes:
    return hmac.new(k, ("hdrcast/v1/" + label).encode("utf-8"), hashlib.sha256).digest()


K = bytes(range(32))
gid = b64u(bytes(range(0xA0, 0xB0)))
host = b64u(bytes(range(0xB0, 0xC0)))
viewer = b64u(bytes(range(0xC0, 0xD0)))
sid_raw = bytes(range(0xD0, 0xE0))
sid = b64u(sid_raw)

server_key = sub(K, "server")
msg_key = sub(K, "msg")
passphrase = b64u(sub(K, "srt"))[:32]
punch_key = sub(K, "punch/" + sid)

# invite: exact JSON bytes (compact separators, non-ASCII kept as UTF-8)
invite_obj = {"v": 1, "s": "http://101.43.23.94:18650", "g": gid, "k": b64u(K), "n": "测试组"}
invite_json = json.dumps(invite_obj, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
invite_code = "hdrcast:" + b64u(invite_json) + "." + b64u(hashlib.sha256(invite_json).digest())[:8]


def envelope(kind: str, key: str, payload: dict) -> dict:
    p = b64u(json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8"))
    m = b64u(hmac.new(msg_key, (kind + "\n" + gid + "\n" + key + "\n" + p).encode("utf-8"), hashlib.sha256).digest())
    return {"p": p, "m": m}


live_payload = {"v": 1, "t": 1758500000000, "host": host, "name": "小明", "since": 1758499000000,
                "cands": ["[2400:aaaa:bbbb:cccc:1122:33ff:fe44:5566]:51234", "192.168.1.5:51235"],
                "codec": "hevc", "mbps": 40, "max": 4, "viewers": 1}
join_payload = {"v": 1, "t": 1758500001000, "sid": sid, "viewer": viewer, "name": "小红",
                "cands": ["[2001:db8::7]:40000"], "latency": 3500, "overhead": 50}
answer_payload = {"v": 1, "t": 1758500002000, "sid": sid, "ok": True, "reason": "",
                  "cands": ["[2400:aaaa:bbbb:cccc:1122:33ff:fe44:5566]:51234"]}

# request authentication
auth_method, auth_path = "POST", "/v1/g/" + gid + "/live/" + host + "/join"
auth_body = json.dumps(envelope("join", host, join_payload), separators=(",", ":")).encode("utf-8")
auth_ts, auth_nonce = 1758500001234, b64u(bytes(range(8)))
auth_msg = "\n".join([auth_method, auth_path, str(auth_ts), auth_nonce, b64u(hashlib.sha256(auth_body).digest())])
auth_mac = b64u(hmac.new(server_key, auth_msg.encode("utf-8"), hashlib.sha256).digest())
empty_hash = b64u(hashlib.sha256(b"").digest())

# control packet: PUNCH from the viewer, ts = 123456789 us
head = b"HDRCP2P1" + bytes([1, 2]) + sid_raw + struct.pack(">QQ", 123456789, 0)
punch = head + hmac.new(punch_key, head, hashlib.sha256).digest()[:16]
head_ack = b"HDRCP2P1" + bytes([2, 1]) + sid_raw + struct.pack(">QQ", 123999999, 123456789)
punch_ack = head_ack + hmac.new(punch_key, head_ack, hashlib.sha256).digest()[:16]
assert len(punch) == 58 and len(punch_ack) == 58

# UDP echo reply for 203.0.113.9:40001 and [2001:db8::9]:40002
nonce16 = bytes(range(0x30, 0x40))
echo_req = b"HDRCECHO" + nonce16
echo_v4 = b"HDRCECHO" + nonce16 + bytes([4]) + struct.pack(">H", 40001) + bytes([203, 0, 113, 9])
echo_v6 = (b"HDRCECHO" + nonce16 + bytes([6]) + struct.pack(">H", 40002)
           + bytes.fromhex("20010db8000000000000000000000009"))

vectors = {
    "comment": "Generated by tests/vectors/make_group_v1.py; see docs/design.md section 8.",
    "groupKey": b64u(K), "gid": gid, "host": host, "viewer": viewer, "sid": sid,
    "serverKey": b64u(server_key), "msgKey": b64u(msg_key), "srtPassphrase": passphrase,
    "punchKey": b64u(punch_key),
    "inviteJson": invite_json.decode("utf-8"), "inviteCode": invite_code,
    "live": {"payload": live_payload, "envelope": envelope("live", host, live_payload)},
    "join": {"payload": join_payload, "envelope": envelope("join", host, join_payload)},
    "answer": {"payload": answer_payload, "envelope": envelope("answer", sid, answer_payload)},
    "auth": {"method": auth_method, "path": auth_path, "body": auth_body.decode("utf-8"), "ts": auth_ts,
             "nonce": auth_nonce, "bodyHash": b64u(hashlib.sha256(auth_body).digest()), "emptyBodyHash": empty_hash,
             "mac": auth_mac, "header": "%d.%s.%s" % (auth_ts, auth_nonce, auth_mac)},
    "punchHex": punch.hex(), "punchAckHex": punch_ack.hex(),
    "echo": {"requestHex": echo_req.hex(), "replyV4Hex": echo_v4.hex(), "replyV6Hex": echo_v6.hex()},
}

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "group-v1.json")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    json.dump(vectors, f, ensure_ascii=False, indent=2)
    f.write("\n")
print("wrote", out)
